    /// <summary>As SYSTEM (same password as the app user in the gvenzl image); new sessions get the role.</summary>
    private async Task GrantCatalogRoleAsync()
    {
        var system = new OracleConnectionStringBuilder(oracle.RequireConnectionString()) { UserID = "system" };
        await using var connection = new OracleConnection(system.ConnectionString);
        try
        {
            await connection.OpenAsync(Ct);
        }
        catch (OracleException ex)
        {
            Assert.Skip($"SYSTEM login not possible: {ex.Message}");
        }

        await using var command = connection.CreateCommand();
        command.CommandText = $"GRANT SELECT_CATALOG_ROLE TO {OracleIdentifier.Quote(Owner)}";
        await command.ExecuteNonQueryAsync(Ct);
    }
