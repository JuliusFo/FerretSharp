        var proposal = SchemaDdl.Align(comparison with { Objects = [row with { Children = children }] }, 0, 1);

        Assert.Equal(["ALTER TABLE \"TEST\".\"KUNDE\" ADD CONSTRAINT \"UQ_NR\" UNIQUE (\"NR\")"], Sql(proposal));
    }

