    [Fact]
    public void New_table_gets_create_table_with_exact_types_defaults_and_not_null()
    {
        var table = Table("AUFTRAG",
        [
            Column("ID", "NUMBER", identity: true),
            Column("NAME", "VARCHAR2", length: 50, charSemantics: true, nullable: false),
            Column("CODE", "VARCHAR2", length: 10, @default: "'X'"),
            Column("LAND", "CHAR", length: 2, defaultOnNull: true, @default: "'DE'"),
            Column("TEXT", "NVARCHAR2", length: 100),
            Column("BETRAG", "NUMBER", precision: 12, scale: 2),
            Column("MENGE", "NUMBER", scale: 0),
            Column("FAKTOR", "NUMBER", scale: 3),
            Column("WERT", "NUMBER"),
            Column("ZEIT", "TIMESTAMP(3)"),
            Column("DATUM", "DATE", nullable: false, @default: "SYSDATE"),
            Column("HASH", "RAW", length: 16),
            Column("NOTIZ", "CLOB"),
            Column("BRUTTO", "NUMBER", isVirtual: true, @default: "\"BETRAG\"*1.19"),
        ]);

        var step = Single(Align(table, null));

        Assert.Equal("AUFTRAG", step.Object);
        Assert.Equal(
            """
            CREATE TABLE "TEST"."AUFTRAG" (
                "ID" NUMBER GENERATED BY DEFAULT AS IDENTITY,
                "NAME" VARCHAR2(50 CHAR) NOT NULL,
                "CODE" VARCHAR2(10 BYTE) DEFAULT 'X',
                "LAND" CHAR(2 BYTE) DEFAULT ON NULL 'DE',
                "TEXT" NVARCHAR2(100),
                "BETRAG" NUMBER(12,2),
                "MENGE" INTEGER,
                "FAKTOR" NUMBER(*,3),
                "WERT" NUMBER,
                "ZEIT" TIMESTAMP(3),
                "DATUM" DATE DEFAULT SYSDATE NOT NULL,
                "HASH" RAW(16),
                "NOTIZ" CLOB,
                "BRUTTO" NUMBER GENERATED ALWAYS AS ("BETRAG"*1.19) VIRTUAL)
            """.ReplaceLineEndings("\n"),
            step.Sql);
        Assert.Contains("Identity ID", step.Warning);
        Assert.Contains("BY DEFAULT", step.Warning);
    }

    [Fact]
    public void New_table_adds_keys_checks_foreign_keys_and_indexes_after_all_tables()
    {
        var kunde = Kunde();
        var auftrag = Table("AUFTRAG",
            [Id, Column("KUNDE_ID", "NUMBER", precision: 10, scale: 0), Column("NR", "VARCHAR2", length: 20), Column("MENGE", "NUMBER")],
            [
                PrimaryKey("SYS_C001", "ID"),
                Unique("UQ_AUFTRAG_NR", "NR"),
                Check("SYS_C002", "MENGE > 0"),
                Check("CK_AUFTRAG_NR", "NR <> 'X'"),
                ForeignKey("FK_AUFTRAG_KUNDE", ["KUNDE_ID"], new TableRef(Ref, "KUNDE"), ["ID"], "CASCADE"),
            ],
            [
                UniqueIndex(Ref, "SYS_C001", On("ID")),
                UniqueIndex(Ref, "UQ_AUFTRAG_NR", On("NR")),
                Index(Ref, "IX_AUFTRAG_KUNDE", On("KUNDE_ID")),
            ]);

        var proposal = Align([auftrag, kunde], []);

        Assert.Equal(
            [
                "CREATE TABLE \"TEST\".\"AUFTRAG\" (\n    \"ID\" NUMBER(10) NOT NULL,\n    \"KUNDE_ID\" NUMBER(10),\n    \"NR\" VARCHAR2(20 BYTE),\n    \"MENGE\" NUMBER)",
                "CREATE TABLE \"TEST\".\"KUNDE\" (\n    \"ID\" NUMBER(10) NOT NULL)",
                "ALTER TABLE \"TEST\".\"AUFTRAG\" ADD PRIMARY KEY (\"ID\")",
                "ALTER TABLE \"TEST\".\"AUFTRAG\" ADD CONSTRAINT \"UQ_AUFTRAG_NR\" UNIQUE (\"NR\")",
                "ALTER TABLE \"TEST\".\"KUNDE\" ADD CONSTRAINT \"PK_KUNDE\" PRIMARY KEY (\"ID\")",
                "ALTER TABLE \"TEST\".\"AUFTRAG\" ADD CHECK (MENGE > 0)",
                "ALTER TABLE \"TEST\".\"AUFTRAG\" ADD CONSTRAINT \"CK_AUFTRAG_NR\" CHECK (NR <> 'X')",
                "ALTER TABLE \"TEST\".\"AUFTRAG\" ADD CONSTRAINT \"FK_AUFTRAG_KUNDE\" FOREIGN KEY (\"KUNDE_ID\") REFERENCES \"TEST\".\"KUNDE\" (\"ID\") ON DELETE CASCADE",
                "CREATE INDEX \"TEST\".\"IX_AUFTRAG_KUNDE\" ON \"TEST\".\"AUFTRAG\" (\"KUNDE_ID\")",
            ],
            Sql(proposal));
        Assert.All(proposal.Steps, s => Assert.Null(s.Warning)); // a new table has no rows to fail on
    }

    [Fact]
