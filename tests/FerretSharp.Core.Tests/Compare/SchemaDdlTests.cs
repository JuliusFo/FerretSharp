                "ALTER TABLE \"TEST\".\"KUNDE\" MODIFY (\"B\" DEFAULT NULL)",
                "ALTER TABLE \"TEST\".\"KUNDE\" MODIFY (\"C\" DEFAULT ON NULL 'N')",
