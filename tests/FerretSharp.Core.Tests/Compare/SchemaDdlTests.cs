    [Fact]
    public void Default_changes_set_replace_or_remove_it()
    {
        var proposal = Align(
            Kunde(Column("A", "CHAR", 1, @default: "'J'"), Column("B", "CHAR", 1), Column("C", "CHAR", 1, @default: "'N'", defaultOnNull: true)),
            Kunde(Column("A", "CHAR", 1, @default: "'N'"), Column("B", "CHAR", 1, @default: "'N'"), Column("C", "CHAR", 1, @default: "'N'")));

        Assert.Equal(
