    private const string Ref = "DEV";
    private const string Tgt = "TEST";

    private static readonly ColumnInfo Id = Column("ID", "NUMBER", precision: 10, scale: 0, nullable: false);

    private static ObjectSnapshot Kunde(params ColumnInfo[] extra) =>
        Table("KUNDE", [Id, .. extra], [PrimaryKey("PK_KUNDE", "ID")], [UniqueIndex(Ref, "PK_KUNDE", On("ID"))]);

    private static DdlProposal Align(ObjectSnapshot? reference, ObjectSnapshot? target, CompareOptions? options = null) =>
        Align([.. reference is null ? Array.Empty<ObjectSnapshot>() : [reference]], [.. target is null ? Array.Empty<ObjectSnapshot>() : [target]], options);

    private static DdlProposal Align(ObjectSnapshot[] reference, ObjectSnapshot[] target, CompareOptions? options = null) =>
        SchemaDdl.Align(Of(options ?? new CompareOptions(Reference: 0), Snapshot(Ref, reference), Snapshot(Tgt, target)), 0, 1);

    private static string[] Sql(DdlProposal proposal) => proposal.Steps.Select(s => s.Sql).ToArray();

    private static DdlStep Single(DdlProposal proposal) => Assert.Single(proposal.Steps);

