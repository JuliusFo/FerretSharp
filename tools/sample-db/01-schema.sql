ALTER TABLE ARTIKEL ADD (HERSTELLER_ID NUMBER(10) CONSTRAINT FK_ARTIKEL_HERSTELLER REFERENCES HERSTELLER, KATEGORIE_ID NUMBER(10) CONSTRAINT FK_ARTIKEL_KATEGORIE REFERENCES KATEGORIE);
ALTER TABLE KUNDEN ADD (ADRESSE_ID NUMBER(10) CONSTRAINT FK_KUNDEN_ADRESSE REFERENCES ADRESSE);
ALTER TABLE AUFTRAG_POSITION ADD (ARTIKEL_ID NUMBER(10) CONSTRAINT FK_POS_ARTIKEL REFERENCES ARTIKEL);

CREATE VIEW V_OFFENE_POSTEN AS SELECT r.RECHNUNG_ID, r.BETRAG, r.FAELLIG_AM FROM RECHNUNG r WHERE r.FAELLIG_AM < SYSDATE;

