-- that does not compile, a wrapped procedure, a large package and two triggers (one disabled).
SET FEEDBACK OFF
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

CREATE OR REPLACE PACKAGE PKG_RECHNUNG AS
  -- Rechnungen erstellen und Beträge berechnen
  TYPE T_POSTEN IS RECORD (AUFTRAG_ID NUMBER, BETRAG NUMBER(12,2));
  C_MWST CONSTANT NUMBER := 0.19;

  FUNCTION BRUTTO(P_NETTO NUMBER) RETURN NUMBER;
  FUNCTION BRUTTO(P_NETTO NUMBER, P_SATZ NUMBER DEFAULT C_MWST) RETURN NUMBER;
  PROCEDURE ERSTELLE(P_AUFTRAG_ID IN NUMBER, P_RECHNUNG_ID OUT NUMBER, P_ZAEHLER IN OUT PLS_INTEGER);
  PROCEDURE OFFENE(P_KUNDE IN KUNDEN%ROWTYPE, P_CURSOR OUT SYS_REFCURSOR);
  PROCEDURE AUFRAEUMEN;
END PKG_RECHNUNG;
/

CREATE OR REPLACE PACKAGE BODY PKG_RECHNUNG AS
  FUNCTION BRUTTO(P_NETTO NUMBER) RETURN NUMBER IS
  BEGIN
    RETURN ROUND(P_NETTO * (1 + C_MWST), 2);
  END;

  FUNCTION BRUTTO(P_NETTO NUMBER, P_SATZ NUMBER DEFAULT C_MWST) RETURN NUMBER IS
  BEGIN
    RETURN ROUND(P_NETTO * (1 + P_SATZ), 2);
  END;

  PROCEDURE ERSTELLE(P_AUFTRAG_ID IN NUMBER, P_RECHNUNG_ID OUT NUMBER, P_ZAEHLER IN OUT PLS_INTEGER) IS
    V_KUNDE_ID AUFTRAG.KUNDE_ID%TYPE;
  BEGIN
    SELECT KUNDE_ID INTO V_KUNDE_ID FROM AUFTRAG WHERE AUFTRAG_ID = P_AUFTRAG_ID;
    SELECT NVL(MAX(RECHNUNG_ID), 0) + 1 INTO P_RECHNUNG_ID FROM RECHNUNG;
    INSERT INTO RECHNUNG (RECHNUNG_ID, AUFTRAG_ID, KUNDE_ID, BETRAG) VALUES (P_RECHNUNG_ID, P_AUFTRAG_ID, V_KUNDE_ID, 0);
    P_ZAEHLER := P_ZAEHLER + 1;
  END;

  PROCEDURE OFFENE(P_KUNDE IN KUNDEN%ROWTYPE, P_CURSOR OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN P_CURSOR FOR
      SELECT * FROM RECHNUNG WHERE KUNDE_ID = P_KUNDE.KUNDE_ID AND GEDRUCKT_AM IS NULL;
  END;

  PROCEDURE AUFRAEUMEN IS
  BEGIN
    DELETE FROM RECHNUNG WHERE BETRAG = 0 AND GEDRUCKT_AM IS NULL;
  END;
END PKG_RECHNUNG;
/

CREATE OR REPLACE FUNCTION KUNDE_UMSATZ(P_KUNDE_ID NUMBER) RETURN NUMBER IS
  V_SUMME NUMBER;
BEGIN
  SELECT NVL(SUM(BETRAG), 0) INTO V_SUMME FROM RECHNUNG WHERE KUNDE_ID = P_KUNDE_ID;
  RETURN V_SUMME;
END;
/

CREATE OR REPLACE PROCEDURE NACHT_LAUF IS
BEGIN
  PKG_RECHNUNG.AUFRAEUMEN;
END;
/

