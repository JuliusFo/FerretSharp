-- A large package: 6,000 lines of constants and comments.
DECLARE
  V_TEXT CLOB;
  V_LINE VARCHAR2(200);
BEGIN
  DBMS_LOB.CREATETEMPORARY(V_TEXT, TRUE);
  V_LINE := 'CREATE OR REPLACE PACKAGE PKG_KONSTANTEN AS' || CHR(10);
  DBMS_LOB.WRITEAPPEND(V_TEXT, LENGTH(V_LINE), V_LINE);
  FOR I IN 1 .. 6000 LOOP
    -- Every fourth line a constant: 6,000 of them would be too large for one package (PLS-00123).
    V_LINE := CASE WHEN MOD(I, 4) = 0 THEN '  C_WERT_' || I || ' CONSTANT NUMBER := ' || I || ';' ELSE '  -- Zeile ' || I || ': Beschreibung des Werts' END || CHR(10);
    DBMS_LOB.WRITEAPPEND(V_TEXT, LENGTH(V_LINE), V_LINE);
  END LOOP;
  V_LINE := 'END PKG_KONSTANTEN;';
  DBMS_LOB.WRITEAPPEND(V_TEXT, LENGTH(V_LINE), V_LINE);
  EXECUTE IMMEDIATE V_TEXT;
END;
/

