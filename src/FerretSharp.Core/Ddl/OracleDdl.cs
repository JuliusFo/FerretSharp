using System.Text;
using FerretSharp.Core.Oracle;
using FerretSharp.Core.Query;
using FerretSharp.Core.Schema;

namespace FerretSharp.Core.Ddl;

/// <summary>
/// The text of every DDL statement FerretSharp writes – the schema comparison's proposal (WP-20) and the designer (WP-23)
/// alike, both run through the schema path (WP-22). One place since R4b (before: <c>DdlText</c> plus statements built in
/// both writers). Names are always quoted exactly as in the dictionary.
/// </summary>
internal static class OracleDdl
{
    public static string Q(string name) => OracleIdentifier.Quote(name);

    private static string T(TableRef table) => OracleIdentifier.Qualify(table.Owner, table.Name);

    // ---- tables ----

    /// <summary><c>CREATE [GLOBAL TEMPORARY ]TABLE t (\n    a,\n    b)[ ORGANIZATION INDEX][ TABLESPACE "X"]</c>: one entry per line.</summary>
    /// <param name="entries">Column definitions (<see cref="ColumnDefinition"/>), then inline constraints.</param>
    /// <param name="tablespace">The tablespace to create it in (WP-67); null for the owner's default.</param>
    public static string CreateTable(TableRef table, IEnumerable<string> entries, bool temporary = false, bool indexOrganized = false, string? tablespace = null) =>
        $"{(temporary ? "CREATE GLOBAL TEMPORARY TABLE" : "CREATE TABLE")} {T(table)} (\n    {string.Join(",\n    ", entries)})"
        + (indexOrganized ? " ORGANIZATION INDEX" : "") + Tablespace(tablespace);

    /// <summary><c> TABLESPACE "X"</c>, or nothing for none (the owner's default).</summary>
    private static string Tablespace(string? tablespace) => string.IsNullOrEmpty(tablespace) ? "" : $" TABLESPACE {Q(tablespace)}";

    public static string DropObject(TableKind kind, TableRef table) => $"DROP {ObjectKeyword(kind)} {T(table)}";

    public static string RenameObject(TableKind kind, TableRef table, string to) => $"ALTER {ObjectKeyword(kind)} {T(table)} RENAME TO {Q(to)}";

    public static string CommentOnTable(TableRef table, string? comment) => $"COMMENT ON TABLE {T(table)} IS {Literal(comment)}";

    public static string ObjectKeyword(TableKind kind) => kind switch
    {
        TableKind.View => "VIEW",
        TableKind.MaterializedView => "MATERIALIZED VIEW",
        _ => "TABLE",
    };

    // ---- columns ----

    /// <summary><c>"NAME" type [AS (…) | identity | DEFAULT …] [NOT NULL]</c> for CREATE TABLE and ADD.</summary>
    public static string ColumnDefinition(ColumnInfo column)
    {
        var sql = new StringBuilder($"{Q(column.Name)} {OracleTypes.DdlType(column)}");
        if (column.IsVirtual)
        {
            sql.Append($" GENERATED ALWAYS AS ({Expression(column.Default ?? "")}) VIRTUAL");
        }
        else if (column.IsIdentity)
        {
            sql.Append(' ').Append(IdentityClause(column));
        }
        else if (column.Default is { } value)
        {
            sql.Append(column.DefaultOnNull ? $" DEFAULT ON NULL {Expression(value)}" : $" DEFAULT {Expression(value)}");
        }

        // Identity and DEFAULT ON NULL columns are NOT NULL by themselves.
        if (!column.Nullable && !column.IsIdentity && !column.DefaultOnNull)
        {
            sql.Append(" NOT NULL");
        }

        return sql.ToString();
    }

    /// <summary>
    /// <c>GENERATED ALWAYS | BY DEFAULT [ON NULL] AS IDENTITY</c>: ALWAYS as the column is (known since WP-42) – BY DEFAULT took
    /// explicit ids the source refuses (review 3.54.0, A15).
    /// </summary>
    private static string IdentityClause(ColumnInfo column) =>
        column.IdentityAlways ? "GENERATED ALWAYS AS IDENTITY"
        : column.DefaultOnNull ? "GENERATED BY DEFAULT ON NULL AS IDENTITY"
        : "GENERATED BY DEFAULT AS IDENTITY";

    /// <summary><c>ALTER TABLE t MODIFY ("C" GENERATED … AS IDENTITY)</c>: how an existing identity column takes given values.</summary>
    public static string ModifyIdentity(TableRef table, string column, ColumnInfo to) => $"ALTER TABLE {T(table)} MODIFY ({Q(column)} {IdentityClause(to)})";

    public static string AddColumn(TableRef table, ColumnInfo column) => $"ALTER TABLE {T(table)} ADD ({ColumnDefinition(column)})";

    public static string DropColumn(TableRef table, string column) => $"ALTER TABLE {T(table)} DROP COLUMN {Q(column)}";

    public static string RenameColumn(TableRef table, string from, string to) => $"ALTER TABLE {T(table)} RENAME COLUMN {Q(from)} TO {Q(to)}";

    /// <summary><c>ALTER TABLE t MODIFY ("C" type)</c>: the type of <paramref name="to"/>.</summary>
    public static string ModifyType(TableRef table, string column, ColumnInfo to) => $"ALTER TABLE {T(table)} MODIFY ({Q(column)} {OracleTypes.DdlType(to)})";

    /// <summary><c>ALTER TABLE t MODIFY ("C" DEFAULT [ON NULL] value)</c>; no value sets <c>DEFAULT NULL</c>.</summary>
    public static string ModifyDefault(TableRef table, string column, string? value, bool onNull) =>
        $"ALTER TABLE {T(table)} MODIFY ({Q(column)} DEFAULT {(onNull ? "ON NULL " : "")}{(value is null ? "NULL" : Expression(value))})";

    public static string ModifyNull(TableRef table, string column, bool nullable) =>
        $"ALTER TABLE {T(table)} MODIFY ({Q(column)} {(nullable ? "NULL" : "NOT NULL")})";

    public static string CommentOnColumn(TableRef table, string column, string? comment) => $"COMMENT ON COLUMN {T(table)}.{Q(column)} IS {Literal(comment)}";

    // ---- constraints ----

    public static string AddConstraint(TableRef table, string clause) => $"ALTER TABLE {T(table)} ADD {clause}";

    public static string DropConstraint(TableRef table, string name) => $"ALTER TABLE {T(table)} DROP CONSTRAINT {Q(name)}";

    public static string RenameConstraint(TableRef table, string from, string to) => $"ALTER TABLE {T(table)} RENAME CONSTRAINT {Q(from)} TO {Q(to)}";

    /// <summary>The kind of step that adds a constraint of this type.</summary>
    public static DdlStepKind AddKind(ConstraintType type) => type switch
    {
        ConstraintType.PrimaryKey or ConstraintType.Unique => DdlStepKind.AddKey,
        ConstraintType.Check => DdlStepKind.AddCheck,
        _ => DdlStepKind.AddForeignKey,
    };

    /// <summary>
    /// The constraint as it follows <c>ADD</c> (or stands in a CREATE TABLE): named unless Oracle generated the name in
    /// the reference, then Oracle names it again. <paramref name="usingIndex"/>: an index of another name backing the key.
    /// <paramref name="indexTablespace"/>: the tablespace of the index a new primary or unique key creates (WP-67) – only
    /// when no index of the table backs the key: Oracle then refuses the clause (ORA-01408) instead of taking that one.
    /// </summary>
    public static string ConstraintClause(ConstraintInfo constraint, Func<TableRef, TableRef> mapTable, string? usingIndex = null, string? indexTablespace = null)
    {
        var sql = new StringBuilder();
        if (!constraint.GeneratedName)
        {
            sql.Append($"CONSTRAINT {Q(constraint.Name)} ");
        }

        switch (constraint.Type)
        {
            case ConstraintType.PrimaryKey:
                sql.Append($"PRIMARY KEY ({Columns(constraint.Columns)})");
                break;
            case ConstraintType.Unique:
                sql.Append($"UNIQUE ({Columns(constraint.Columns)})");
                break;
            case ConstraintType.Check:
                sql.Append($"CHECK ({Expression(constraint.Condition ?? "")})");
                break;
            case ConstraintType.ForeignKey:
                var to = mapTable(constraint.References ?? throw new ArgumentException($"Foreign key {constraint.Name} without referenced table.", nameof(constraint)));
                sql.Append($"FOREIGN KEY ({Columns(constraint.Columns)}) REFERENCES {T(to)} ({Columns(constraint.ReferencedColumns)})");
                if (constraint.DeleteRule is "CASCADE" or "SET NULL")
                {
                    sql.Append($" ON DELETE {constraint.DeleteRule}");
                }

                break;
            default:
                throw new ArgumentException($"No DDL for constraint type {constraint.Type}.", nameof(constraint));
        }

        if (constraint.Deferrable)
        {
            sql.Append(constraint.InitiallyDeferred ? " DEFERRABLE INITIALLY DEFERRED" : " DEFERRABLE");
        }

        if (usingIndex is not null)
        {
            sql.Append($" USING INDEX ({usingIndex})");
        }
        else if (!string.IsNullOrEmpty(indexTablespace) && constraint.Type is ConstraintType.PrimaryKey or ConstraintType.Unique)
        {
            sql.Append($" USING INDEX{Tablespace(indexTablespace)}");
        }

        if (!constraint.Enabled)
        {
            sql.Append(constraint.Validated ? " DISABLE VALIDATE" : " DISABLE");
        }
        else if (!constraint.Validated)
        {
            sql.Append(" ENABLE NOVALIDATE");
        }

        return sql.ToString();
    }

    // ---- indexes ----

    /// <summary><c>CREATE [UNIQUE |BITMAP ]INDEX "O"."N" ON "O"."T" (…)</c>; null for index types it cannot write (domain, cluster …).</summary>
    /// <param name="tablespace">
    /// The tablespace to create it in (WP-67); null for the owner's default. Never the <see cref="IndexInfo.Tablespace"/> of
    /// a reference: the schema comparison does not carry tablespaces over (they differ between databases).
    /// </param>
    public static string? CreateIndex(IndexInfo index, string name, string owner, string table, string? tablespace = null)
    {
        var bitmap = index.IndexType.Contains("BITMAP", StringComparison.Ordinal);
        if (!bitmap && !index.IndexType.Contains("NORMAL", StringComparison.Ordinal))
        {
            return null;
        }

        var kind = bitmap ? "BITMAP " : index.Unique ? "UNIQUE " : "";
        var sql = new StringBuilder($"CREATE {kind}INDEX {OracleIdentifier.Qualify(owner, name)} ON {OracleIdentifier.Qualify(owner, table)} ({IndexColumns(index.Columns)})");
        if (index.IndexType.EndsWith("/REV", StringComparison.Ordinal))
        {
            sql.Append(" REVERSE");
        }

        sql.Append(Tablespace(tablespace));

        if (!index.Visible)
        {
            sql.Append(" INVISIBLE");
        }

        return sql.ToString();
    }

    public static string DropIndex(string owner, string name) => $"DROP INDEX {OracleIdentifier.Qualify(owner, name)}";

    public static string RenameIndex(string owner, string from, string to) => $"ALTER INDEX {OracleIdentifier.Qualify(owner, from)} RENAME TO {Q(to)}";

    public static string IndexColumns(IEnumerable<IndexColumn> columns) =>
        string.Join(", ", columns.Select(c => (c.IsExpression ? c.Name : Q(c.Name)) + (c.Descending ? " DESC" : "")));

    public static string Columns(IEnumerable<string> names) => string.Join(", ", names.Select(Q));

    // ---- triggers (WP-26) ----

    public static string EnableTrigger(string owner, string name) => $"ALTER TRIGGER {OracleIdentifier.Qualify(owner, name)} ENABLE";

    // ---- expressions and literals ----

    /// <summary>
    /// An expression (default, check condition, virtual column) as it stands inside DDL. Oracle keeps a trailing
    /// <c>-- comment</c> in the dictionary text; it ends with a line break here, or it would swallow the <c>,</c> or
    /// <c>)</c> that follows.
    /// </summary>
    public static string Expression(string expression) =>
        SqlTokenizer.Tokenize(expression) is [.., { Kind: SqlTokenKind.Comment } last] && last.Value.StartsWith("--", StringComparison.Ordinal)
            ? expression + "\n"
            : expression;

    /// <summary>
    /// The expression can stand inside a single DDL statement (R4a): no <c>;</c>, no bind variable (Oracle allows none in
    /// DDL, the schema path refuses them) and matching brackets. Everything else the database checks.
    /// </summary>
    public static bool FitsInStatement(string expression)
    {
        var depth = 0;
        foreach (var token in SqlTokenizer.Tokenize(expression))
        {
            if (token.Kind == SqlTokenKind.Bind || token.IsSymbol(";") || (token.IsSymbol(")") && --depth < 0))
            {
                return false;
            }

            if (token.IsSymbol("("))
            {
                depth++;
            }
        }

        return depth == 0;
    }

    /// <summary>A string literal for COMMENT ON.</summary>
    public static string Literal(string? text) => OracleLiteral.Text(text);
}
