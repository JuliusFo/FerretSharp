-- FerretSharp's built-in audit template (WP-26). Syntax and rules: docs/audit-templates.md.
-- Every insert, update and delete on the table writes a row into the audit table: the new values for I and U, the old
-- values for D. An update that changes no value writes nothing: the comparable columns are compared NULL-safe, a LOB
-- (not comparable with <>) counts as changed when the update sets it (UPDATING). FALSE keeps the condition valid for any
-- mix of columns. Comments here stay in the template; comments in the trigger source would end up in the database.

-- @audit-table   AUDIT_{table}
-- @trigger       {table}_AUDIT
-- @table-comment Changes to {table}, written by trigger {trigger}

-- @columns
AUDIT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL  -- Running number of the audit row
AUDIT_USER  VARCHAR2(64)  NOT NULL  -- Client identifier of the session, else the database user
AUDIT_TRANS CHAR(1)       NOT NULL  -- I = insert, U = update, D = delete
AUDIT_TIME  DATE          NOT NULL  -- Time of the change
AUDIT_SID   NUMBER        NOT NULL  -- Audit session id of the change (USERENV SESSIONID)
-- @base-columns nullable

-- @trigger-source
CREATE OR REPLACE TRIGGER {trigger}
AFTER DELETE OR INSERT OR UPDATE ON {table}
FOR EACH ROW
DECLARE
  audit_trans CHAR(1);
BEGIN
  IF DELETING THEN
    INSERT INTO {audit_table} (AUDIT_USER, AUDIT_TRANS, AUDIT_TIME, AUDIT_SID{each}, {column}{end})
    VALUES (SUBSTRB(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER), 1, 64),
            'D', SYSDATE, SYS_CONTEXT('USERENV', 'SESSIONID'){each}, :old.{column}{end});
  ELSE
    IF INSERTING THEN
      audit_trans := 'I';
    ELSIF FALSE{each comparable}
       OR (:new.{column} <> :old.{column} OR (:new.{column} IS NULL AND :old.{column} IS NOT NULL) OR (:new.{column} IS NOT NULL AND :old.{column} IS NULL)){end}{each incomparable}
       OR UPDATING('{name}'){end}
    THEN
      audit_trans := 'U';
    ELSE
      RETURN;
    END IF;
    INSERT INTO {audit_table} (AUDIT_USER, AUDIT_TRANS, AUDIT_TIME, AUDIT_SID{each}, {column}{end})
    VALUES (SUBSTRB(NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), USER), 1, 64),
            audit_trans, SYSDATE, SYS_CONTEXT('USERENV', 'SESSIONID'){each}, :new.{column}{end});
  END IF;
END;
