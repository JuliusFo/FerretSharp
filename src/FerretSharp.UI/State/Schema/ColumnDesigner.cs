/// <summary>
/// A column in the edit mode of the "Columns" view (WP-23, stage 2), as the fields show it: the type split into a base type
/// and its numbers (<c>VARCHAR2</c> + 50 + CHAR, <c>NUMBER</c> + 12 + 2, <c>TIMESTAMP</c> + 3), numbers as typed.
/// </summary>
public sealed class DesignColumn
{
    /// <summary>Base types offered in the type list, in this order; a column of another type keeps its own.</summary>
    public static readonly IReadOnlyList<string> Types =
    [
        "VARCHAR2", "NVARCHAR2", "CHAR", "NCHAR", "NUMBER", "FLOAT", "DATE", "TIMESTAMP", "TIMESTAMP WITH TIME ZONE",
        "TIMESTAMP WITH LOCAL TIME ZONE", "CLOB", "NCLOB", "BLOB", "RAW",
    ];

    /// <summary>The column in the table; null for a new one.</summary>
    public ColumnInfo? Before { get; private init; }

    public bool IsNew => Before is null;

    public string Name { get; set; } = "";

    /// <summary>Base type: <c>VARCHAR2</c>, <c>NUMBER</c>, <c>TIMESTAMP WITH TIME ZONE</c> ….</summary>
    public string Type { get; set; } = "VARCHAR2";

    /// <summary>Length, the precision of a number, or the digits of a timestamp's fractional seconds – as typed.</summary>
    public string Size { get; set; } = "";

    /// <summary>The scale of a number, as typed.</summary>
    public string Scale { get; set; } = "";

    /// <summary>VARCHAR2/CHAR count characters, not bytes.</summary>
    public bool CharSemantics { get; set; }

    public bool NotNull { get; set; }

    public string Default { get; set; } = "";

    public bool DefaultOnNull { get; set; }

    /// <summary>Only for new columns: <c>GENERATED BY DEFAULT AS IDENTITY</c>.</summary>
    public bool Identity { get; set; }

    public string Comment { get; set; } = "";

    public bool Dropped { get; set; }

    /// <summary>Virtual and identity columns: only name and comment are the designer's.</summary>
    public bool OnlyNameAndComment => Before is { IsVirtual: true } or { IsIdentity: true };

    /// <summary>The type takes a length (text, RAW), a precision and scale (NUMBER, FLOAT) or fractional digits (TIMESTAMP).</summary>
    public bool HasSize => OracleTypes.HasLength(Type) || Type is "NUMBER" or "FLOAT" || OracleTypes.IsTimestamp(Type);

    public bool HasScale => Type == "NUMBER";

    public bool HasSemantics => OracleTypes.HasLengthSemantics(Type);

    /// <summary>
    /// The CHAR box as shown: <see cref="CharSemantics"/> for VARCHAR2/CHAR, always set for NVARCHAR2/NCHAR (they count
    /// characters), clear for any other type. <see cref="CharSemantics"/> itself stays, so switching back restores it.
    /// </summary>
    public bool ShowsCharSemantics => HasSemantics ? CharSemantics : OracleTypes.IsNational(Type) && OracleTypes.HasLength(Type);

    public static DesignColumn Of(ColumnInfo column)
    {
        var row = new DesignColumn
        {
            Before = column,
            Name = column.Name,
            NotNull = !column.Nullable,
            Default = column.Default?.Trim() ?? "",
            DefaultOnNull = column.DefaultOnNull,
            Identity = column.IsIdentity,
            Comment = column.Comment ?? "",
            CharSemantics = column.CharSemantics,
        };

        if (OracleTypes.IsTimestamp(column.DataType) && column.DataType.IndexOf('(', StringComparison.Ordinal) is var open and > 0
            && column.DataType.IndexOf(')', open) is var close and > 0)
        {
            row.Type = (column.DataType[..open] + column.DataType[(close + 1)..]).Trim();
            row.Size = column.DataType[(open + 1)..close];
        }
        else
        {
            row.Type = column.DataType;
            row.Size = N(OracleTypes.HasLength(column.DataType) ? column.Length : column.Precision);
            row.Scale = OracleTypes.IsNumber(column.DataType) ? N(column.Scale) : "";
        }

        return row;
    }

    public static DesignColumn New(bool charSemantics) => new() { Type = "VARCHAR2", Size = "50", CharSemantics = charSemantics };

    /// <summary>Takes over what the user entered in <paramref name="other"/> (the column as it should be), keeping <see cref="Before"/>.</summary>
    public void CopyFrom(DesignColumn other)
    {
        (Name, Type, Size, Scale, CharSemantics, NotNull) = (other.Name, other.Type, other.Size, other.Scale, other.CharSemantics, other.NotNull);
        (Default, DefaultOnNull, Identity, Comment, Dropped) = (other.Default, other.DefaultOnNull, other.Identity, other.Comment, other.Dropped);
    }

    /// <summary>The same entries as a new column (it is not in the table yet).</summary>
    public DesignColumn AsNew()
    {
        var column = new DesignColumn();
        column.CopyFrom(this);
        column.Dropped = false;
        return column;
    }

    /// <summary>The column as it should be, or what is wrong with the numbers typed.</summary>
    public (ColumnInfo? Column, string? Problem) ToColumn()
    {
        var label = Name.Length > 0 ? Name : "?";
        if (!TryNumber(Size, out var size) || !TryNumber(Scale, out var scale))
        {
            return (null, TextFormat.Format(SchemaViewText.Designer_NotANumber, label));
        }

        var type = Type;
        int? length = null, precision = null, numberScale = null;
        if (OracleTypes.IsTimestamp(Type))
        {
            type = Type.Length > "TIMESTAMP".Length ? $"TIMESTAMP({size ?? 6}){Type["TIMESTAMP".Length..]}" : $"TIMESTAMP({size ?? 6})";
        }
        else if (OracleTypes.HasLength(Type))
        {
            length = size;
        }
        else if (Type is "NUMBER" or "FLOAT")
        {
            (precision, numberScale) = (size, Type == "NUMBER" ? scale : null);
        }

        var column = new ColumnInfo(
            Name.Trim(), type, length, HasSemantics ? CharSemantics : Type is "NVARCHAR2" or "NCHAR", precision, numberScale,
            Nullable: !NotNull && !Identity, IsIdentity: Identity, Default: Default.Trim().Length > 0 ? Default.Trim() : null,
            Position: Before?.Position ?? 0, Comment: Comment.Length > 0 ? Comment : null, IsVirtual: Before?.IsVirtual ?? false,
            DefaultOnNull: DefaultOnNull);

        // A virtual or identity column keeps its definition – the draft only renames or comments it.
        return Before is { } before && OnlyNameAndComment
            ? (before with { Name = column.Name, Comment = column.Comment }, null)
            : (column, null);
    }

    /// <summary>The draft differs from the table in this column (for marking the row).</summary>
    public bool IsChanged => Dropped || Before is null || ToColumn() is not ({ } column, null) || !Same(Before, column);

    private static bool Same(ColumnInfo a, ColumnInfo b) =>
        a.Name == b.Name && OracleTypes.DdlType(a) == OracleTypes.DdlType(b) && a.Nullable == b.Nullable && a.DefaultOnNull == b.DefaultOnNull
        && (a.Default?.Trim() ?? "") == (b.Default?.Trim() ?? "") && (a.Comment ?? "") == (b.Comment ?? "");

    private static bool TryNumber(string text, out int? value)
    {
        value = null;
        if (string.IsNullOrWhiteSpace(text) || text.Trim() == "*")
        {
            return true;
        }

        if (int.TryParse(text.Trim(), NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var number))
        {
            value = number;
            return true;
        }

        return false;
    }

    private static string N(int? value) => value?.ToString(CultureInfo.InvariantCulture) ?? "";
}

/// <summary>The edit mode of a table tab: its draft, and how the last run failed (shown again after the tab was rebuilt).</summary>
public sealed record DesignerSession(ColumnDesigner Draft, DdlRunResult? Failure = null);

/// <summary>A constraint the edit mode adds, as its fields show it.</summary>
public sealed class DesignConstraint
{
    private readonly SuggestedName _name = new();

    public ConstraintType Type { get; set; } = ConstraintType.Unique;

    /// <summary>The name as the field shows it. Setting it is typing it: it no longer follows type and columns – empty follows again.</summary>
    public string Name
    {
        get => _name.Value;
        set => _name.Type(value);
    }

    /// <summary>The suggested name for its type and columns, unless the user typed one (<see cref="ColumnDesigner.SuggestName"/>).</summary>
    internal void Suggest(string name) => _name.Follow(name);

    public List<string> Columns { get; } = [];

    public string Condition { get; set; } = "";

    public TableRef? References { get; set; }

    /// <summary>Referenced columns, one per entry of <see cref="Columns"/>.</summary>
    public List<string> ReferencedColumns { get; } = [];

    /// <summary><c>CASCADE</c>, <c>SET NULL</c> or empty for none.</summary>
    public string DeleteRule { get; set; } = "";

    public bool WithIndex { get; set; } = true;

    /// <summary>The referenced column for the key column at <paramref name="at"/> (a foreign key); missing entries before it stay empty.</summary>
    public void SetReferenced(int at, string? column)
    {
        while (ReferencedColumns.Count <= at)
        {
            ReferencedColumns.Add("");
        }

        ReferencedColumns[at] = column ?? "";
    }

    public ConstraintDraft ToDraft() => new(
        OracleIdentifier.Normalize(Name), Type, [.. Columns], Type == ConstraintType.Check ? Condition : null,
        Type == ConstraintType.ForeignKey ? References : null, Type == ConstraintType.ForeignKey ? [.. ReferencedColumns] : null,
        DeleteRule.Length > 0 ? DeleteRule : null, WithIndex);
}

/// <summary>
/// An existing constraint in the edit mode, as its fields show it: its name, a check's condition, a foreign key's delete
/// rule – renamed or changed, it becomes a <see cref="ConstraintEdit"/>.
/// </summary>
public sealed class ExistingConstraint
{
    public ExistingConstraint(ConstraintInfo before)
    {
        ArgumentNullException.ThrowIfNull(before);
        Before = before;
        Name = before.Name;
        Condition = before.Condition?.Trim() ?? "";
        DeleteRule = Rule(before.DeleteRule);
    }

    /// <summary>The constraint in the table.</summary>
    public ConstraintInfo Before { get; }

    public string Name { get; set; }

    /// <summary>A check's condition, as typed.</summary>
    public string Condition { get; set; }

    /// <summary>A foreign key's <c>CASCADE</c>, <c>SET NULL</c> or empty for none.</summary>
    public string DeleteRule { get; set; }

    /// <summary>A renamed key's index of the same name gets the new name too.</summary>
    public bool RenameIndex { get; set; } = true;

    public bool IsRenamed => OracleIdentifier.Normalize(Name) != Before.Name;

    /// <summary>Renamed, a check with another condition, a foreign key with another delete rule.</summary>
    public bool IsChanged => IsRenamed
                             || (Before.Type == ConstraintType.Check && Condition.Trim() != (Before.Condition ?? "").Trim())
                             || (Before.Type == ConstraintType.ForeignKey && DeleteRule != Rule(Before.DeleteRule));

    public ConstraintEdit ToEdit() => new(
        Before.Name, OracleIdentifier.Normalize(Name), Before.Type == ConstraintType.Check ? Condition : null,
        Before.Type == ConstraintType.ForeignKey && DeleteRule.Length > 0 ? DeleteRule : null, RenameIndex);

    /// <summary>Takes over what the user entered in <paramref name="other"/>, keeping <see cref="Before"/>.</summary>
    public void CopyFrom(ExistingConstraint other)
    {
        ArgumentNullException.ThrowIfNull(other);
        (Name, Condition, DeleteRule, RenameIndex) = (other.Name, other.Condition, other.DeleteRule, other.RenameIndex);
    }

    /// <summary>The dictionary's <c>NO ACTION</c> is no rule.</summary>
    private static string Rule(string? rule) => rule is "CASCADE" or "SET NULL" ? rule : "";
}

/// <summary>The tabs of the edit mode; the draft keeps the one shown.</summary>
public enum DesignerSection
{
    Columns,
    Constraints,
    Audit,

    /// <summary>Property lines for new columns of a table the C# model maps.</summary>
    CSharp,

    /// <summary>The DDL with its problems and warnings.</summary>
    Script,
}

/// <summary>
/// The edit mode of the "Columns" view (WP-23, stage 2): the table's columns and constraints as editable rows, and the
/// <see cref="TableDraft"/> they make. Plain state – the view renders it, <see cref="TableDesign"/> writes the DDL.
/// </summary>
public sealed class ColumnDesigner
{
    public ColumnDesigner(TableDetails table, IReadOnlyList<ConstraintInfo> constraints)
    {
        ArgumentNullException.ThrowIfNull(table);
        Table = table;
        TableName = table.Table.Name;
        Columns = table.Columns.Select(DesignColumn.Of).ToList();
        Existing = constraints.Where(c => !c.IsColumnNotNull).Select(c => new ExistingConstraint(c)).ToList();
    }

    /// <summary>The tab shown; kept across a <see cref="Rebase"/>.</summary>
    public DesignerSection Section { get; set; }

    public TableDetails Table { get; }

    /// <summary>The table's name for suggested constraint names; a new table's changes as it is typed (WP-23, stage 3).</summary>
    public string TableName { get; set; } = "";

    public List<DesignColumn> Columns { get; }

    /// <summary>The table's constraints, to rename, change or drop (NOT NULL checks belong to their columns).</summary>
    public IReadOnlyList<ExistingConstraint> Existing { get; }

    /// <summary>Names of existing constraints to drop (their names in the table).</summary>
    public HashSet<string> DroppedConstraints { get; } = new(StringComparer.Ordinal);

    public List<DesignConstraint> AddedConstraints { get; } = [];

    public bool HasChanges => ColumnsChanged || ConstraintsChanged;

    public bool ColumnsChanged => Columns.Any(c => c.IsChanged);

    public bool ConstraintsChanged => DroppedConstraints.Count > 0 || AddedConstraints.Count > 0 || Existing.Any(c => c.IsChanged);

    /// <summary>
    /// Audit table and trigger go into the plan (WP-26): created, or brought up to date with the draft. Null until the view
    /// knows whether the table has an audit table (<see cref="AuditAtStart"/>).
    /// </summary>
    public bool? WithAudit { get; set; }

    /// <summary>
    /// Where the audit box starts: on when the designer was opened for the audit table; on for a table with an audit table
    /// unless the setting says otherwise (<see cref="Core.Settings.AppSettings.SyncAuditInDesigner"/>); off for a table
    /// without one, which is the normal case.
    /// </summary>
    public static bool AuditAtStart(bool openedForAudit, bool hasAuditTable, bool syncByDefault) =>
        openedForAudit || (hasAuditTable && syncByDefault);

    /// <summary>The names of the columns as drafted (renamed, new), without dropped ones – for constraint columns.</summary>
    public IReadOnlyList<string> ColumnNames => Columns.Where(c => !c.Dropped && c.Name.Trim().Length > 0).Select(c => c.Name.Trim()).ToList();

    /// <summary>A new column at the end (Oracle adds columns there), with the text semantics most columns of the table use.</summary>
    public DesignColumn AddColumn()
    {
        var text = Table.Columns.Where(c => OracleTypes.HasLengthSemantics(c.DataType)).ToList();
        var column = DesignColumn.New(charSemantics: text.Count > 0 && text.Count(c => c.CharSemantics) * 2 >= text.Count);
        Columns.Add(column);
        return column;
    }

    /// <summary>A new column goes away; an existing one is marked dropped (and comes back on the second call).</summary>
    public void ToggleDrop(DesignColumn column)
    {
        if (column.IsNew)
        {
            Columns.Remove(column);
        }
        else
        {
            column.Dropped = !column.Dropped;
        }
    }

    public DesignConstraint AddConstraint(ConstraintType type)
    {
        var constraint = new DesignConstraint { Type = type };
        AddedConstraints.Add(constraint);
        SuggestName(constraint);
        return constraint;
    }

    /// <summary>The suggested name for its type and columns, unless the user typed one.</summary>
    public void SuggestName(DesignConstraint constraint)
    {
        ArgumentNullException.ThrowIfNull(constraint);
        var taken = Existing.Select(c => c.Before.Name).Concat(Existing.Select(c => OracleIdentifier.Normalize(c.Name)))
            .Concat(AddedConstraints.Where(c => c != constraint).Select(c => c.Name));
        constraint.Suggest(TableDesign.SuggestConstraintName(TableName, constraint.Type, constraint.Columns, constraint.References?.Name, taken));
    }

    /// <summary>An existing constraint is dropped – or, the second time, kept again.</summary>
    public void ToggleDropConstraint(string name)
    {
        if (!DroppedConstraints.Remove(name))
        {
            DroppedConstraints.Add(name);
        }
    }

    /// <summary>Another kind of constraint: the name follows, unless typed.</summary>
    public void SetType(DesignConstraint constraint, ConstraintType type)
    {
        ArgumentNullException.ThrowIfNull(constraint);
        constraint.Type = type;
        SuggestName(constraint);
    }

    /// <summary>
    /// A column for the constraint, at the end. A foreign key's referenced column follows the key of the referenced table,
    /// position by position (once its structure is known, <see cref="Referenced"/>).
    /// </summary>
    public void AddColumn(DesignConstraint constraint, string? column)
    {
        ArgumentNullException.ThrowIfNull(constraint);
        if (string.IsNullOrEmpty(column) || constraint.Columns.Contains(column))
        {
            return;
        }

        constraint.Columns.Add(column);
        if (constraint.References is { } references && Referenced.TryGetValue(references, out var target))
        {
            constraint.ReferencedColumns.Add(KeyColumn(target, constraint.Columns.Count - 1));
        }

        SuggestName(constraint);
    }

    /// <summary>Takes the column at <paramref name="at"/> out of the constraint, with its referenced column.</summary>
    public void RemoveColumn(DesignConstraint constraint, int at)
    {
        ArgumentNullException.ThrowIfNull(constraint);
        constraint.Columns.RemoveAt(at);
        if (at < constraint.ReferencedColumns.Count)
        {
            constraint.ReferencedColumns.RemoveAt(at);
        }

        SuggestName(constraint);
    }

    /// <summary>
    /// The foreign key references <paramref name="table"/> (null: none chosen). Its referenced columns are the table's
    /// primary key, position by position, as soon as the table's structure is known – the view loads it if
    /// <see cref="Referenced"/> lacks it, then calls <see cref="Learn"/>.
    /// </summary>
    public void Reference(DesignConstraint constraint, TableRef? table)
    {
        ArgumentNullException.ThrowIfNull(constraint);
        constraint.ReferencedColumns.Clear();
        constraint.References = table;
        SuggestName(constraint);
        FillReferenced(constraint);
    }

    /// <summary>
    /// The structures of the tables new foreign keys reference, as loaded (their keys and column types); kept across a
    /// <see cref="Rebase"/>.
    /// </summary>
    public Dictionary<TableRef, TableDetails> Referenced { get; } = [];

    /// <summary>A referenced table's structure arrived: foreign keys on it without referenced columns get its key.</summary>
    public void Learn(TableDetails table)
    {
        ArgumentNullException.ThrowIfNull(table);
        Referenced[table.Table.Ref] = table;
        foreach (var constraint in AddedConstraints.Where(c => c.References == table.Table.Ref))
        {
            FillReferenced(constraint);
        }
    }

    /// <summary>The columns another table offers to reference; this table's as drafted; null while not loaded.</summary>
    public IReadOnlyList<string>? ColumnsOf(TableRef table) =>
        table == Table.Table.Ref ? ColumnNames : Referenced.TryGetValue(table, out var details) ? details.Columns.Select(c => c.Name).ToList() : null;

    private void FillReferenced(DesignConstraint constraint)
    {
        if (constraint is { References: { } references, ReferencedColumns.Count: 0 } && Referenced.TryGetValue(references, out var target))
        {
            constraint.ReferencedColumns.AddRange(constraint.Columns.Select((_, i) => KeyColumn(target, i)));
        }
    }

    /// <summary>The primary key's column at a position; the first column where the key has none.</summary>
    private static string KeyColumn(TableDetails table, int at) => table.PrimaryKey.ElementAtOrDefault(at) ?? table.Columns[0].Name;

    /// <summary>
    /// The same draft laid over the table as it is now – after DDL that stopped halfway (WP-23): the draft says how the table
    /// should be, so what already ran drops out by itself. A column is found by the name it should have (renamed, added),
    /// otherwise by its old name (not renamed yet); a dropped column that is gone and a constraint already added or dropped
    /// are done. An existing constraint is found the same way; one gone meanwhile (a check replaced halfway) takes its edit
    /// along – the new check shows as a constraint of its own then.
    /// </summary>
    public ColumnDesigner Rebase(TableDetails table, IReadOnlyList<ConstraintInfo> constraints)
    {
        var next = new ColumnDesigner(table, constraints);
        var added = new List<DesignColumn>();
        foreach (var row in Columns)
        {
            var target = next.Columns.FirstOrDefault(c => c.Before!.Name == row.Name.Trim() && !row.Dropped)
                         ?? (row.Before is { } before ? next.Columns.FirstOrDefault(c => c.Before!.Name == before.Name) : null);
            if (target is not null)
            {
                target.CopyFrom(row);
            }
            else if (!row.Dropped)
            {
                added.Add(row.AsNew());
            }
        }

        next.Columns.AddRange(added);
        foreach (var row in Existing)
        {
            var target = next.Existing.FirstOrDefault(c => c.Before.Name == OracleIdentifier.Normalize(row.Name))
                         ?? next.Existing.FirstOrDefault(c => c.Before.Name == row.Before.Name);
            target?.CopyFrom(row);
        }

        var existing = next.Existing.Select(c => c.Before.Name).ToHashSet(StringComparer.Ordinal);
        next.DroppedConstraints.UnionWith(DroppedConstraints.Where(existing.Contains));
        next.AddedConstraints.AddRange(AddedConstraints.Where(c => c.Name.Length == 0 || !existing.Contains(OracleIdentifier.Normalize(c.Name))));
        foreach (var (reference, details) in Referenced)
        {
            next.Referenced[reference] = details;
        }

        (next.WithAudit, next.Section) = (WithAudit, Section);
        return next;
    }

    /// <summary>The draft, and what is wrong with the fields before the designer can check it (numbers that are none).</summary>
    public (TableDraft Draft, IReadOnlyList<string> Problems) ToDraft()
    {
        var problems = new List<string>();
        var columns = new List<ColumnDraft>();
        foreach (var row in Columns)
        {
            var (column, problem) = row.ToColumn();
            if (problem is not null)
            {
                problems.Add(problem);
            }

            // A column whose numbers are none stays as it is, so the rest can still be checked.
            columns.Add(new ColumnDraft(row.Before?.Name, column ?? row.Before ?? new ColumnInfo(row.Name, row.Type, null, false, null, null, true, false, null, 0), row.Dropped));
        }

        var draft = new TableDraft(columns)
        {
            DroppedConstraints = [.. DroppedConstraints],
            AddedConstraints = AddedConstraints.Select(c => c.ToDraft()).ToList(),
            ChangedConstraints = Existing.Where(c => c.IsChanged && !DroppedConstraints.Contains(c.Before.Name)).Select(c => c.ToEdit()).ToList(),
        };
        return (draft, problems);
    }
}
